    fun search(query: String): List<AllahName> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return names

        return names.filter { item ->
            item.id.toString() == q ||
            item.arabic.contains(q, ignoreCase = true) ||
            item.transliterationBn.contains(q, ignoreCase = true) ||
            item.transliterationEn.contains(q, ignoreCase = true) ||
            item.meaningBn.contains(q, ignoreCase = true) ||
            item.meaningEn.contains(q, ignoreCase = true) ||
            item.fazilatBn.contains(q, ignoreCase = true) ||
            item.category.contains(q, ignoreCase = true)
        }
    }
